/**
 * Hexadecimal color string regular expression
 */
export const HEX_COLOR_STRING_REGEXP = /^([\dA-Fa-f]{2})([\dA-Fa-f]{2})([\dA-Fa-f]{2})$/;

/**
 * Hexadecimal color string regular expression (short form)
 */
export const HEX_COLOR_STRING_REGEXP_SHORT = /^([\dA-Fa-f])([\dA-Fa-f])([\dA-Fa-f])$/;
